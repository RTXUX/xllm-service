#pragma once

#include <absl/synchronization/mutex.h>

#include "chat_template/jinja_chat_template.h"
#include "common/coro.h"
#include "common/types.h"
#include "common/xllm/output.h"

namespace xllm_service {

// Store request-related data
struct Request {
  // model name
  std::string model;

  // request id generated by service
  std::string service_request_id;

  // whether to stream the response
  bool stream = false;

  // whether to return usage
  bool include_usage = false;

  bool offline = false;

  // input prompt
  std::string prompt;

  // input messages
  ChatMessages messages;

  // token ids of prompt
  std::vector<int32_t> token_ids;

  // instance routing
  Routing routing;

  // the number of generated tokens
  int64_t num_generated_tokens = 0;

  // the estimated TTFT obtained from the TTFT predictor
  int64_t estimated_ttft = 0;

  // arrival timestamp (milliseconds since epoch)
  int64_t arrival_time_ms = 0;

  // TTFT SLO from request JSON (milliseconds)
  int64_t ttft_slo_ms = 0;

  // estimated prefill processing time from TimePredictor (milliseconds)
  int64_t estimated_processing_time_ms = 0;

  // output callback
  OutputCallback output_callback;

  // timeout callback, called when request is discarded due to TTFT SLO expiration
  std::function<void()> timeout_callback = nullptr;

  // trace callback
  std::function<void(const std::string&)> trace_callback = nullptr;

  // Expected absolute wall-clock time (ms since epoch) when this request's prefill
  // will complete. Set at dispatch time, used for PREFILL_DONE correction feedback.
  int64_t expected_prefill_done_ms = 0;

  // dispatch callback
  // This callback will be called in a detached coroutine after the request is scheduled.
  std::function<CoroTask()> dispatch_callback = nullptr;

  absl::Mutex mutex;
  bool is_scheduled = false;

  // true for elastic pool requests: forces max_tokens=1 (prefill-only)
  bool prefill_only = false;

  // max output tokens requested by the client; 0 means unset
  int32_t max_tokens = 0;

  // LstImhPolicy coordinator pre-updates metrics after assigning an instance;
  // process_request_queue checks this flag to avoid double-updating.
  bool metrics_already_updated = false;
};

}  // namespace xllm_service